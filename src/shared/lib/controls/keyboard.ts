const supportedKeys = new Set(Object.values(sdlKeys));

const physicalKeyNames = new Map(
  Object.entries(sdlKeys).map(([code, key]) => [key, code]),
);

export const sdlKeyDisplayName = (key: string): string =>
  physicalKeyNames.get(key) ?? key;

export const sdlKeyFromCode = (code: string): string | undefined =>
  Object.prototype.hasOwnProperty.call(sdlKeys, code)
    ? sdlKeys[code]
    : undefined;

export const getEmulatorShortcutKeys = (
  settings: Settings,
  id: string,
): readonly string[] =>
  settings.emulatorShortcuts?.[id] ??
  emulatorShortcuts.find((shortcut) => shortcut.id === id)?.keys ??
  [];

// Existing gamepad settings use KeyboardEvent.key, including unsided modifiers.
const legacyKeys: Record<string, string[]> = {
  Alt: ["LALT", "RALT"],
  Control: ["LCTRL", "RCTRL"],
  Shift: ["LSHIFT", "RSHIFT"],
  Meta: ["LGUI", "RGUI"],
  Enter: ["RETURN", "KP_ENTER"],
  " ": ["SPACE"],
  "-": ["MINUS"],
  "=": ["EQUALS"],
  "[": ["LEFTBRACKET"],
  "]": ["RIGHTBRACKET"],
  "\\": ["BACKSLASH"],
  ";": ["SEMICOLON"],
  "'": ["APOSTROPHE"],
  "`": ["GRAVE"],
  ",": ["COMMA"],
  ".": ["PERIOD"],
  "/": ["SLASH"],
};

const joypadKeyNames = (key: string): string[] => {
  if (Array.isArray(legacyKeys[key])) return legacyKeys[key];
  if (/^[a-z0-9]$/i.test(key)) return [key.toUpperCase()];
  const physical = sdlKeyFromCode(key);
  if (physical) return [physical];
  throw new Error(`Unsupported key: ${key}`);
};

export const makeBinjgbIni = (settings: Settings): string => {
  const lines = [
    "# Generated by GB Studio",
    `ps2-keyboard=${settings.ps2KeyboardSupported ? 1 : 0}`,
  ];
  lines.push("ps2-keys=all", "joypad=none", "shortcuts=none");
  const controls = {
    up: settings.customControlsUp ?? defaultJoypadControls.customControlsUp,
    down: settings.customControlsDown ?? defaultJoypadControls.customControlsDown,
    left: settings.customControlsLeft ?? defaultJoypadControls.customControlsLeft,
    right: settings.customControlsRight ?? defaultJoypadControls.customControlsRight,
    a: settings.customControlsA ?? defaultJoypadControls.customControlsA,
    b: settings.customControlsB ?? defaultJoypadControls.customControlsB,
    start: settings.customControlsStart ?? defaultJoypadControls.customControlsStart,
    select: settings.customControlsSelect ?? defaultJoypadControls.customControlsSelect,
  };
  const joypadAssigned = new Set<string>();
  for (const [button, keys] of Object.entries(controls)) {
    const mapped = [...new Set((keys ?? []).flatMap(joypadKeyNames))];
    for (const key of mapped) {
      if (joypadAssigned.has(key))
        throw new Error(`Conflicting PS/2 joypad key: ${key}`);
      joypadAssigned.add(key);
    }
    lines.push(`joypad-${button}=${mapped.join(",") || "none"}`);
  }
  if (settings.emulatorShortcutsEnabled === false)
    return lines.join("\n") + "\n";
  const assigned = new Set<string>();
  for (const shortcut of emulatorShortcuts) {
    const keys = [...new Set(getEmulatorShortcutKeys(settings, shortcut.id))];
    for (const key of keys) {
      if (!supportedKeys.has(key))
        throw new Error(`Invalid shortcut key: ${key}`);
      if (assigned.has(key))
        throw new Error(`Conflicting shortcut key: ${key}`);
      assigned.add(key);
    }
    lines.push(`shortcut-${shortcut.id}=${keys.join(",") || "none"}`);
  }
  return lines.join("\n") + "\n";
};
